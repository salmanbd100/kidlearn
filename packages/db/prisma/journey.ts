/**
 * Adds the activity-type coverage and the Ocean World lessons the child journey
 * needs. Runs after `seed.ts` has created the worlds, subjects and the English
 * `letter-a` video assets it reuses.
 */
export async function seedJourney(prisma: PrismaClient): Promise<void> {
  const worlds = new Map(
    (await prisma.world.findMany({ select: { id: true, slug: true } })).map(
      (world) => [world.slug, world.id],
    ),
  );
  const jungle = worlds.get("jungle");
  const ocean = worlds.get("ocean");
  if (jungle === undefined || ocean === undefined) {
    throw new Error("Worlds are missing — run `pnpm db:seed` first.");
  }

  // FR-WORLD-05: Ocean World was published without the mascot its card themes
  // itself with, which is why its home tile rendered empty.
  await prisma.world.update({
    where: { id: ocean },
    data: { mascotAssetId: await upsertAsset(prisma, MEDIA.oceanMascot) },
  });

  // Ocean World had no lessons at all, so tapping it opened an empty world. Its
  // topic hangs off `science`, which is published — `mathematics` is in draft,
  // and a draft subject hides every topic under it from the student query.
  const science = await prisma.subject.findUnique({
    where: { slug: "science" },
    select: { id: true },
  });
  if (science === null) {
    throw new Error("Subject `science` is missing — run `pnpm db:seed` first.");
  }

  const oceanLife = await prisma.topic.upsert({
    where: { subjectId_slug: { subjectId: science.id, slug: "ocean-life" } },
    update: { status: "published" },
    create: {
      slug: "ocean-life",
      name: "Ocean Life",
      sortOrder: 1,
      gradeLevels: ["NURSERY", "KG1"],
      status: "published",
      subjectId: science.id,
    },
  });

  for (const language of ["en", "bn"] as const) {
    await prisma.topicTranslation.upsert({
      where: { topicId_language: { topicId: oceanLife.id, language } },
      update: {},
      create: {
        topicId: oceanLife.id,
        language,
        name: language === "en" ? "Ocean Life" : "সমুদ্রের প্রাণী",
      },
    });
  }

  const topics = new Map<string, string>([["ocean-life", oceanLife.id]]);
  const alphabet = await prisma.topic.findFirst({
    where: { slug: "alphabet" },
    select: { id: true },
  });
  if (alphabet === null) {
    throw new Error("Topic `alphabet` is missing — run `pnpm db:seed` first.");
  }
  topics.set("alphabet", alphabet.id);

  // The films are `seed.ts`'s, reused rather than duplicated: one clip standing
  // in for every lesson is the honest shape of a placeholder library.
  const videoEn = id("000000000402");
  const videoBn = id("000000000403");

  for (const lesson of LESSONS) {
    const topicId = topics.get(lesson.topicSlug);
    if (topicId === undefined) continue;

    const [activityId, quizId, posterId, introEnId, introBnId] =
      await Promise.all([
        prisma.activity
          .upsert({
            where: { id: lesson.activity.id },
            update: {
              definition: lesson.activity.definition,
              status: "published",
            },
            create: {
              id: lesson.activity.id,
              type: lesson.activity.type,
              status: "published",
              schemaVersion: 1,
              definition: lesson.activity.definition,
            },
          })
          .then((activity) => activity.id),
        upsertQuiz(prisma, lesson.quiz),
        upsertAsset(prisma, lesson.poster),
        upsertAsset(prisma, lesson.intro.en.audio),
        upsertAsset(prisma, lesson.intro.bn.audio),
      ]);

    const row = {
      title: lesson.title,
      sortOrder: lesson.sortOrder,
      gradeLevels: ["NURSERY", "KG1"] as const,
      status: "published" as const,
      worldId: lesson.worldSlug === "jungle" ? jungle : ocean,
      activityId,
      quizId,
      conceptsIntroduced: lesson.conceptsIntroduced,
    };

    const created = await prisma.lesson.upsert({
      where: { topicId_slug: { topicId, slug: lesson.slug } },
      update: { ...row, gradeLevels: [...row.gradeLevels] },
      create: {
        slug: lesson.slug,
        topicId,
        ...row,
        gradeLevels: [...row.gradeLevels],
      },
    });

    const en = {
      title: lesson.titleTranslations.en,
      introScript: lesson.intro.en.script,
      introAudioAssetId: introEnId,
      videoAssetId: videoEn,
      videoPosterAssetId: posterId,
    };
    await prisma.lessonTranslation.upsert({
      where: { lessonId_language: { lessonId: created.id, language: "en" } },
      update: en,
      create: { lessonId: created.id, language: "en", ...en },
    });

    const bn = {
      title: lesson.intro.bn.title,
      introScript: lesson.intro.bn.script,
      introAudioAssetId: introBnId,
      videoAssetId: lesson.video === "both" ? videoBn : videoEn,
      // No Bangla poster anywhere: the English still is the `assetFallbacks`
      // path file 17 reports (FR-I18N-01), and it is worth keeping exercised.
      videoPosterAssetId: posterId,
    };
    await prisma.lessonTranslation.upsert({
      where: { lessonId_language: { lessonId: created.id, language: "bn" } },
      update: bn,
      create: { lessonId: created.id, language: "bn", ...bn },
    });
  }

  // `letter-a-practice` is published with an activity but no quiz, which drops a
  // child from step 3 straight to the reward — four steps, not the five every
  // other lesson has.
  const practice = await prisma.lesson.findFirst({
    where: { slug: "letter-a-practice" },
    select: { id: true, quizId: true },
  });
  if (practice !== null && practice.quizId === null) {
    await prisma.lesson.update({
      where: { id: practice.id },
      data: { quizId: await upsertQuiz(prisma, PRACTICE_QUIZ) },
    });
  }

  console.log(`Seeded ${LESSONS.length} journey lessons + the practice quiz.`);
}
