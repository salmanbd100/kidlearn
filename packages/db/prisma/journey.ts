async function upsertAsset(
  prisma: PrismaClient,
  fixture: MediaFixture,
): Promise<string> {
  const data = {
    url: fixture.url,
    kind: fixture.kind,
    language: fixture.language ?? null,
  };
  const asset = await prisma.mediaAsset.upsert({
    where: { id: fixture.id },
    update: data,
    create: { id: fixture.id, ...data },
  });
  return asset.id;
}

