import type { Prisma, PrismaClient } from "@prisma/client";

/**
 * The lessons that make the *whole* child journey walkable in development — one
 * per activity type, each with a quiz, narration, a video and a poster, so every
 * branch of the five-step player (`document/user-journey-manual.md` §4.3–4.5)
 * has content behind it. `seed.ts` already covers `drag_drop`; this file adds
 * `trace`, `match` and `puzzle`, and gives Ocean World the lessons it was
 * published without.
 *
 * Two different kinds of url appear below, and the difference is not cosmetic:
 *
 * - **`MediaAsset.url`** (mascots, video, posters, narration) is a plain column,
 *   so it takes a relative `/dev/...` path that Next serves straight out of
 *   `apps/web/public`. Generated by `apps/web/scripts/generate-dev-media.sh`.
 * - **Payload-embedded assets** (activity items, quiz options) go through
 *   `ImageAssetRefSchema`, which requires `https://` (`packages/types/src/primitives.ts`)
 *   — a relative path does not parse. Those point at `placehold.co`, which is a
 *   real host, so the images render once the origin is listed in
 *   `MEDIA_ASSET_HOSTS`. Payload *audio* has no such free host: it stays on the
 *   unresolvable `cdn.kidlearn.test` and is silent until a real CDN is wired up.
 */

const PLACEHOLDER_CDN = "https://placehold.co";
/** Unresolvable on purpose — see this file's header. */
const ASSET_CDN = "https://cdn.kidlearn.test";

type LocalizedText = { en: string; bn: string };

function picture(
  text: string,
  colour: string,
  alt: LocalizedText,
): Prisma.InputJsonValue {
  return {
    kind: "image",
    url: `${PLACEHOLDER_CDN}/400x400/${colour}/FFFFFF/png?text=${encodeURIComponent(text)}`,
    alt,
  };
}

function voice(name: string): Prisma.InputJsonValue {
  return {
    en: { kind: "audio", url: `${ASSET_CDN}/audio/en/${name}.mp3` },
    bn: { kind: "audio", url: `${ASSET_CDN}/audio/bn/${name}.mp3` },
  };
}

