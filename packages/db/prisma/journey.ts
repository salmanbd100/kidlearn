async function upsertQuiz(
  prisma: PrismaClient,
  fixture: QuizFixture,
): Promise<string> {
  const quiz = await prisma.quiz.upsert({
    where: { id: fixture.id },
    update: { title: fixture.title, status: "published" },
    create: { id: fixture.id, title: fixture.title, status: "published" },
  });

  for (const [index, question] of fixture.questions.entries()) {
    const data = {
      quizId: quiz.id,
      format: question.format,
      sortOrder: index + 1,
      schemaVersion: 1,
      definition: question.definition,
    };
    await prisma.quizQuestion.upsert({
      where: { id: question.id },
      update: data,
      create: { id: question.id, ...data },
    });
  }
  return quiz.id;
}

