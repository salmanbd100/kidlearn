import { describe, expect, it } from "vitest";
import { provenanceLabel } from "./job-labels";

describe("provenanceLabel", () => {
  it("names the MCP client as self-reported, and who asked", () => {
    expect(
      provenanceLabel({
        source: "mcp",
        client: { name: "claude-code", version: "2.1.0" },
        requestedBy: "Ayesha",
      }),
    ).toBe(
      "Written by claude-code 2.1.0 (self-reported) via MCP · requested by Ayesha",
    );
  });

  it("says Gemini for a Gemini job, without a requester it never recorded", () => {
    expect(
      provenanceLabel({ source: "gemini", client: null, requestedBy: null }),
    ).toBe("Generated by Gemini");
  });

  it("does not let an MCP client pass itself off as Gemini", () => {
    expect(
      provenanceLabel({
        source: "mcp",
        client: { name: "Gemini", version: null },
        requestedBy: null,
      }),
    ).toBe("Written by Gemini (self-reported) via MCP");
  });

  it("does not invent a client name the assistant never sent", () => {
    expect(
      provenanceLabel({ source: "mcp", client: null, requestedBy: "Ayesha" }),
    ).toBe("Written by an AI assistant via MCP · requested by Ayesha");
  });
});
