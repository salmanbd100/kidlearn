import type {
  AiJobStatus,
  AiJobSummary,
  AiJobType,
  AiReviewDecision,
} from "@kidlearn/types";
import { formatRelative } from "@/shared/lib/relative-time";

/** Names what the work is rather than the cost-bucket enum ("Audio" hides intro vs story page). */
export const AI_JOB_TYPE_LABELS: Record<AiJobType, string> = {
  lesson: "Lesson",
  story: "Story",
  quiz: "Quiz",
  audio: "Narration",
  image: "Illustration",
};

export const AI_JOB_STATUS_LABELS: Record<AiJobStatus, string> = {
  pending: "Pending",
  generating: "Generating",
  awaiting_review: "Awaiting review",
  approved: "Approved",
  rejected: "Rejected",
  failed: "Failed",
};

const AI_DECISION_LABELS: Record<AiReviewDecision, string> = {
  approve: "Approved as generated",
  edit_then_approve: "Edited by a reviewer, then approved",
  reject: "Rejected",
};

export function decisionLabel(
  decision: AiReviewDecision,
  status: AiJobStatus,
): string {
  if (decision === "edit_then_approve" && status === "awaiting_review") {
    return "Edited by a reviewer — not yet approved";
  }
  return AI_DECISION_LABELS[decision];
}

export function formatRelativeAge(
  isoTimestamp: string,
  now: Date = new Date(),
): string {
  return formatRelative(new Date(isoTimestamp), "en", now);
}

/**
 * Short form for a queue row. An MCP client names itself, so its name never stands alone: a client
 * calling itself "Gemini" must not read as a Gemini row.
 */
export function sourceLabel(
  job: Pick<AiJobSummary, "source" | "client">,
): string {
  if (job.source === "gemini") return "Gemini";
  return job.client === null
    ? "AI assistant"
    : `AI assistant · ${job.client.name}`;
}

/**
 * The reviewer's provenance line (FR-AI-10). The client name is the assistant's own claim, so it is labelled
 * as such; what is not in doubt is which admin's token submitted it.
 */
export function provenanceLabel(
  job: Pick<AiJobSummary, "source" | "client" | "requestedBy">,
): string {
  const requester =
    job.requestedBy === null ? "" : ` · requested by ${job.requestedBy}`;
  if (job.source === "gemini") return `Generated by Gemini${requester}`;

  const client =
    job.client === null
      ? "an AI assistant"
      : `${job.client.name}${job.client.version === null ? "" : ` ${job.client.version}`} (self-reported)`;
  return `Written by ${client} via MCP${requester}`;
}
